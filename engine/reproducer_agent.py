"""Reproducer Subagent: Red-to-Green Test Synthesis & Differential Verification.

Synthesizes self-contained, dependency-minimal reproduction test scripts that
deterministically trigger failure on broken baseline code (Red) and verify
complete recovery when executed against the patched worktree (Green).
"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, Optional

from pydantic import BaseModel

from mcp_server.ast_graph_mcp import ASTSubGraphResponse, SyscallTelemetry


class ReproductionResult(BaseModel):
    """Encapsulates differential test execution outcomes across unpatched and patched worktrees."""
    reproduction_script_path: str
    reproduced_on_baseline: bool
    baseline_error: Optional[str] = None
    passed_on_candidate: bool
    candidate_output: str
    red_to_green_confirmed: bool


class ReproducerAgent:
    """Synthesizes and runs isolated standalone reproduction scripts."""

    def __init__(self, workspace_root: Optional[str | Path] = None):
        self.workspace_root = Path(workspace_root or os.getcwd()).resolve()

    def generate_reproduction_script(
        self,
        output_path: Optional[str | Path] = None,
    ) -> Path:
        """Generates a standalone, dependency-minimal reproduction script."""
        script_path = Path(
            output_path or (self.workspace_root / ".autopatch" / "reproduce_issue.py")
        ).resolve()
        script_path.parent.mkdir(parents=True, exist_ok=True)

        reproduction_script_code = '''"""Automated Red-to-Green Minimal Issue Reproducer.

Autogenerated by AutoPatch-Kernel Reproducer Subagent.
"""
import sys
from target_app.processor import process_payment_order


def run_reproduction_cases():
    print("[REPRODUCER] Running regression test case 1: Boundary Promo ZeroDivision...")
    case_1 = {
        "order_id": "REPRO-001",
        "customer": {"customer_id": "C-1", "tier": "GOLD"},
        "items": [{"sku": "SKU-1", "price": 100.0, "quantity": 1}],
        "active_promos_count": 4,  # Triggers ZeroDivisionError in unpatched code!
        "jurisdiction": "US-CA",
    }
    res_1 = process_payment_order(case_1)
    assert res_1["status"] == "APPROVED"
    assert res_1["discount_applied"] >= 0.0

    print("[REPRODUCER] Running regression test case 2: Modern API v2 Tier Profile...")
    case_2 = {
        "order_id": "REPRO-002",
        "customer": {
            "customer_id": "C-2",
            "tier_profile": {"tier_level": "PLATINUM", "loyalty_score": 900},  # Triggers KeyError in unpatched!
        },
        "items": [{"sku": "SKU-2", "price": 250.0, "quantity": 1}],
        "active_promos_count": 1,
        "jurisdiction": "EU-DE",
    }
    res_2 = process_payment_order(case_2)
    assert res_2["status"] == "APPROVED"
    assert res_2["discount_applied"] > 0.0

    print("[REPRODUCER] All reproduction cases executed successfully!")


if __name__ == "__main__":
    try:
        run_reproduction_cases()
        sys.exit(0)
    except Exception as runtime_fault_instance:
        print(
            f"[REPRODUCER_CRASH] {type(runtime_fault_instance).__name__}: {str(runtime_fault_instance)}",
            file=sys.stderr,
        )
        sys.exit(1)
'''
        script_path.write_text(reproduction_script_code, encoding="utf-8")
        return script_path

    def verify_red_to_green(
        self,
        baseline_dir: str | Path,
        candidate_dir: str | Path,
    ) -> ReproductionResult:
        """Executes reproduction script against both baseline and candidate worktrees.
        
        Enforces Red-to-Green transition invariant:
        1. Baseline directory MUST fail (confirming real fault reproduction).
        2. Candidate worktree directory MUST pass (confirming bug resolution).
        """
        synthesized_script_path = self.generate_reproduction_script()

        # 1. Execute against baseline (MUST FAIL / RED)
        baseline_process_environment = os.environ.copy()
        baseline_process_environment["PYTHONPATH"] = (
            f"{baseline_dir}{os.pathsep}{baseline_process_environment.get('PYTHONPATH', '')}"
        )
        baseline_invocation_process = subprocess.run(
            [sys.executable, str(synthesized_script_path)],
            cwd=str(baseline_dir),
            capture_output=True,
            text=True,
            env=baseline_process_environment,
        )
        reproduced_on_baseline = baseline_invocation_process.returncode != 0
        baseline_error_diagnostic = (
            baseline_invocation_process.stderr.strip() or baseline_invocation_process.stdout.strip()
        )

        # 2. Execute against candidate patch (MUST SUCCEED / GREEN)
        candidate_process_environment = os.environ.copy()
        candidate_process_environment["PYTHONPATH"] = (
            f"{candidate_dir}{os.pathsep}{candidate_process_environment.get('PYTHONPATH', '')}"
        )
        candidate_invocation_process = subprocess.run(
            [sys.executable, str(synthesized_script_path)],
            cwd=str(candidate_dir),
            capture_output=True,
            text=True,
            env=candidate_process_environment,
        )
        passed_on_candidate = candidate_invocation_process.returncode == 0
        candidate_output_diagnostic = candidate_invocation_process.stdout.strip()

        differential_red_to_green_confirmed = reproduced_on_baseline and passed_on_candidate

        return ReproductionResult(
            reproduction_script_path=str(synthesized_script_path),
            reproduced_on_baseline=reproduced_on_baseline,
            baseline_error=baseline_error_diagnostic,
            passed_on_candidate=passed_on_candidate,
            candidate_output=candidate_output_diagnostic,
            red_to_green_confirmed=differential_red_to_green_confirmed,
        )
